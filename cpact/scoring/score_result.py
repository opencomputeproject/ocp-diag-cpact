class ScorePrinter:
    """
    Renders scoring results and category breakdowns to the console.

    This class is responsible for presenting score information using
    Rich-based table formatting and console visualization utilities.
    It converts scoring results into readable summaries to aid users
    in understanding execution performance and scoring contributions.

    Responsibilities
    ----------------
    - Display overall execution scores.
    - Render category-level score breakdowns.
    - Present profile-based score adjustments.
    - Generate visually formatted console reports.
    - Improve score readability through structured output.
    """

    def __init__(self, console: Optional[Console] = None, logger: Optional[Any] = None):

        self.manager = ScoreManager()
        self.console = console or Console()
        self.logger = logger

    def _colored_status(self, status):

        if status == "PASS":
            return "\033[92mPASS\033[0m"

        elif status == "FAIL":
            return "\033[91mFAIL\033[0m"

        elif status == "PARTIAL":
            return "\033[93mPARTIAL\033[0m"

        return status

    def print_summary(
        self,
        include_nested: bool = True,
    ):
        """
        Print summary of all recipe executions.
        """

        if include_nested:
            results = self.manager.get_all_results()
        else:
            results = self.manager.get_root_results()

        rows = []

        total_score = 0.0
        total_duration = 0.0

        highest = 0.0
        lowest = 100.0

        passed = 0
        failed = 0
        partial = 0
        not_executed = 0

        for index, result in enumerate(results, start=1):

            ctx = self.manager.get_context(result.execution_id)

            schema = "N/A"
            map_status = "N/A"

            for cat in result.categories:

                if cat.name == "Schema":
                    schema = cat.status

                elif cat.name == "Map":
                    map_status = cat.status

            score = result.final_score

            # Determine recipe status
            if ctx.schema_exists and not ctx.schema_passed:
                status = "FAIL"

            elif ctx.map_exists and not ctx.map_passed:
                status = "FAIL"

            elif ctx.total_steps == 0:
                status = "NOT EXECUTED"

            elif ctx.failed_steps > 0:
                status = "FAIL"

            elif ctx.passed_steps == ctx.total_steps:
                status = "PASS"

            else:
                status = "PARTIAL"

            if status == "PASS":
                passed += 1
            elif status == "FAIL":
                failed += 1
            elif status == "PARTIAL":
                partial += 1
            elif status == "NOT EXECUTED":
                not_executed += 1

            duration = 0.0

            if ctx.start_time and ctx.end_time:
                duration = ctx.end_time - ctx.start_time

            total_duration += duration
            total_score += score

            highest = max(highest, score)
            lowest = min(lowest, score)

            rows.append(
                [
                    index,
                    result.recipe_name,
                    result.execution_id,
                    ReportColor.status(schema),
                    ReportColor.status(map_status),
                    f"{ctx.passed_steps}/{ctx.total_steps}",
                    ReportColor.score(score),
                    ReportColor.status(status),
                    f"{duration:.2f}s",
                ]
            )

        table = tabulate(
            rows,
            headers=[
                "#",
                "Recipe",
                "Execution ID",
                "Schema",
                "Map",
                "Steps",
                "Score",
                "Status",
                "Duration",
            ],
            tablefmt="fancy_grid",
            stralign="left",
            numalign="center",
        )

        self.logger.info("\n%s", table)

        avg = total_score / len(results) if results else 0

        stats_rows = [
            ["Recipes Executed", len(results)],
            ["Passed", ReportColor.status(f"PASS ({passed})")],
            ["Failed", ReportColor.status(f"FAIL ({failed})")],
            ["Partial", ReportColor.status(f"PARTIAL ({partial})")],
            ["Not Executed", ReportColor.status(f"NOT EXECUTED ({not_executed})")],
            ["Average Score", ReportColor.score(avg)],
            # ["Highest Score", ReportColor.score(highest)],
            # ["Lowest Score", ReportColor.score(lowest)],
            ["Total Duration", f"{total_duration:.2f}s"],
        ]

        stats_table = tabulate(
            stats_rows,
            headers=["Metric", "Value"],
            tablefmt="fancy_grid",
            stralign="left",
        )

        self.logger.info("\n%s", stats_table)

    def build_table(self, execution_id: str) -> Table:
        """Build (but do not print) the score table for an execution."""
        result = self.manager.calculate(execution_id)
        table = Table(box=HEAVY_HEAD, show_lines=False)
        table.add_column("Category", style="bold cyan", no_wrap=True)
        table.add_column("Score", justify="right")
        table.add_column("Max", justify="right")
        table.add_column("Status", justify="center")

        for category in result.categories:
            if not category.present:
                continue
            status_style = self._status_style(category.status)
            table.add_row(
                category.name,
                f"{category.earned:.2f}",
                f"{category.maximum:.2f}",
                f"[{status_style}]{category.status}[/{status_style}]",
            )
        return table

    @staticmethod
    def _status_style(status: str) -> str:
        """Pick a colour for a status string."""
        if status == "PASS":
            return "green"
        if status == "FAIL":
            return "red"
        return "yellow"

    def pretty_print(self, execution_id: str) -> None:
        """Print a full, framed score report for an execution."""
        result = self.manager.calculate(execution_id)
        rule = "=" * 52
        self.console.print(rule)
        self.console.print()
        self.console.print("[bold]Recipe Execution Score[/bold]")
        self.console.print()
        self.console.print(f"Recipe Name : {result.recipe_name}")
        self.console.print(f"Execution ID: {result.execution_id}")
        self.console.print()
        self.console.print(self.build_table(execution_id))
        self.console.print()
        self.console.print(f"[bold]Final Score : {result.final_score:.2f}[/bold]")
        if result.profile_score:
            self.console.print(f"Profile Bonus: {result.profile_score:.2f}")
        self.console.print()
        self.console.print(rule)

    def print_all_detailed_reports(self):

        results = self.manager.get_all_results()

        for result in results:
            self.print_detailed_report(result.execution_id)

    def _build_event_table(
        self,
        events,
        headers,
        item_key="name",
        empty_message="No data available",
    ):
        """
        Generic helper to build a tabulated report for any event type.

        Args:
            events: List of Event objects.
            headers: List of column headers.
            item_key: Metadata key to use for the second column.
            empty_message: Message shown when no events exist.
        """

        rows = []

        for index, event in enumerate(events, start=1):

            md = event.metadata or {}

            item = (
                md.get(item_key)
                or md.get("file")
                or md.get("step")
                or md.get("rule")
                or md.get("name")
                or "-"
            )

            message = md.get("message", "")
            rows.append(
                [
                    index,
                    item,
                    "PASS" if event.passed else "FAIL",
                    md.get("score", "-"),
                    md.get("max_score", "-"),
                    message,
                ]
            )

        if not rows:
            rows.append(
                [
                    "-",
                    "-",
                    "-",
                    "-",
                    "-",
                    empty_message,
                ]
            )

        return tabulate(
            rows,
            headers=headers,
            tablefmt="fancy_grid",
        )

    def _build_schema_table(self, events):

        return self._build_event_table(
            events,
            headers=[
                "#",
                "Schema File",
                "Status",
                "Score",
                "Max",
                "Remarks",
            ],
            item_key="file",
            empty_message="No schema validation",
        )

    def _group_events(self, ctx):
        grouped = {
            EventType.SCHEMA_VALIDATION: [],
            EventType.MAP_VALIDATION: [],
            EventType.EXECUTION_STEP: [],
            EventType.PROFILE_SCORE: [],
            EventType.NESTED_RECIPE: [],
        }
        for event in ctx.events:
            grouped.setdefault(event.event_type, []).append(event)
        return grouped

    def _build_map_table(self, events):

        return self._build_event_table(
            events,
            headers=[
                "#",
                "Map File",
                "Status",
                "Score",
                "Max",
                "Remarks",
            ],
            item_key="file",
            empty_message="No map validation",
        )

    def _build_step_table(self, events):

        return self._build_event_table(
            events,
            headers=[
                "#",
                "Step",
                "Status",
                "Score",
                "Max",
                "Remarks",
            ],
            item_key="step",
            empty_message="No execution steps",
        )

    def _print_section(self, title, table):

        self.logger.info("")
        self.logger.info("=" * 80)
        self.logger.info(title)
        self.logger.info("=" * 80)
        self.logger.info("\n%s", table)

    def _build_summary_table(self, result, ctx):

        schema = "-"
        map_score = "-"
        execution = "-"

        for category in result.categories:

            if category.name == "Schema":
                schema = f"{category.earned:.0f}/{category.maximum:.0f}"

            elif category.name == "Map":
                map_score = f"{category.earned:.0f}/{category.maximum:.0f}"

            elif category.name == "Execution":
                execution = f"{category.earned:.0f}/{category.maximum:.0f}"

        rows = [
            ["Schema Score", schema],
            ["Map Score", map_score],
            ["Execution Score", execution],
            ["Passed Steps", f"{ctx.passed_steps}/{ctx.total_steps}"],
            ["Profile Bonus", f"{result.profile_score:.2f}"],
            ["Final Score", f"{result.final_score:.2f}"],
        ]

        return tabulate(
            rows,
            headers=["Metric", "Value"],
            tablefmt="fancy_grid",
        )

    def print_detailed_report(self, execution_id):
        result = self.manager.calculate(execution_id)
        ctx = self.manager.get_context(execution_id)

        grouped = self._group_events(ctx)

        self.logger.info("\n")
        self.logger.info("=" * 120)
        self.logger.info("DETAILED RECIPE REPORT")
        self.logger.info("=" * 120)

        self.logger.info("Recipe Name : %s", result.recipe_name)
        self.logger.info("Execution ID: %s", execution_id)

        if ctx.start_time:
            self.logger.info(
                "Started     : %s",
                datetime.fromtimestamp(ctx.start_time),
            )

        if ctx.end_time:
            self.logger.info(
                "Finished    : %s",
                datetime.fromtimestamp(ctx.end_time),
            )

        if ctx.start_time and ctx.end_time:
            self.logger.info(
                "Duration    : %.2f seconds",
                ctx.end_time - ctx.start_time,
            )

        self._print_section(
            "1. SCHEMA VALIDATION",
            self._build_schema_table(grouped[EventType.SCHEMA_VALIDATION]),
        )

        self._print_section(
            "2. MAP VALIDATION",
            self._build_map_table(grouped[EventType.MAP_VALIDATION]),
        )

        # self._print_section(
        #     "3. EXECUTION STEPS",
        #     self._build_step_table(
        #         grouped[EventType.EXECUTION_STEP]
        #     ),
        # )

        self._print_section(
            "4. RECIPE SUMMARY",
            self._build_summary_table(result, ctx),
        )

    def print_framework_report(self):

        results = self.manager.get_root_results()

        self.logger.info("\n")
        # self.logger.info("=" * 120)
        # self.logger.info("FRAMEWORK EXECUTION REPORT")
        # self.logger.info("=" * 120)

        # for result in results:

