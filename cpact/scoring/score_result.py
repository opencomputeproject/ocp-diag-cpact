class TreeRenderer:
    """
    Renders execution hierarchies as annotated text trees.

    The renderer visualizes parent-child recipe relationships and
    associated scoring information in a hierarchical structure,
    helping users understand aggregate score composition and
    execution dependencies.

    Responsibilities
    ----------------
    - Display recipe execution relationships.
    - Render parent-child execution trees.
    - Annotate tree nodes with score information.
    - Visualize aggregate scoring structures.
    - Improve score analysis and troubleshooting.
    """

    def __init__(self, manager: Optional[ScoreManager] = None) -> None:
        """Create a renderer bound to ``manager`` (defaults to the singleton)."""
        self.manager = manager or ScoreManager()

    def _score_for(self, execution_id: str, use_tree_score: bool) -> float:
        """Return the score to annotate a node with."""
        if use_tree_score:
            return self.manager.calculate_tree_score(execution_id)
        return self.manager.calculate(execution_id).final_score

    def render_tree(self, execution_id: str, use_tree_score: bool = False) -> str:
        """Return a string rendering of the subtree rooted at ``execution_id``.

        Parameters
        ----------
        execution_id:
            The root of the subtree to render.
        use_tree_score:
            When ``True`` each node shows its aggregate (step-weighted) tree
            score; when ``False`` (default) each node shows its own local score.

        Raises
        ------
        KeyError
            If ``execution_id`` is unknown.
        """
        context = self.manager.get_context(execution_id)
        if context is None:
            raise KeyError(f"Unknown execution_id: {execution_id!r}")

        score = self._score_for(execution_id, use_tree_score)
        lines: List[str] = [f"{context.recipe_name} ({score:.1f})"]
        self._render_children(execution_id, "", use_tree_score, lines)
        return "\n".join(lines)

    def _render_children(
        self,
        execution_id: str,
        prefix: str,
        use_tree_score: bool,
        lines: List[str],
    ) -> None:
        """Recursively append child lines using box-drawing connectors."""
        context = self.manager.get_context(execution_id)
        if context is None:
            return
        children = list(context.child_execution_ids)
        for index, child_id in enumerate(children):
            child = self.manager.get_context(child_id)
            if child is None:
                continue
            is_last = index == len(children) - 1
            connector = "└── " if is_last else "├── "
            score = self._score_for(child_id, use_tree_score)
            lines.append(f"{prefix}{connector}{child.recipe_name} ({score:.1f})")
            child_prefix = prefix + ("    " if is_last else "│   ")
            self._render_children(child_id, child_prefix, use_tree_score, lines)

    def print_tree(self, execution_id: str, use_tree_score: bool = False) -> None:
        """Print the rendered tree to stdout."""
        print(self.render_tree(execution_id, use_tree_score))


