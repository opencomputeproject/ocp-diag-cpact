class ReportGenerator:
    """
    Generates structured score reports in multiple output formats.

    Provides export capabilities for scoring results, allowing
    execution data to be serialized into JSON, Markdown, and HTML
    report formats for reporting, auditing, dashboards, and
    automation workflows.

    Responsibilities
    ----------------
    - Generate JSON reports.
    - Generate Markdown reports.
    - Generate HTML reports.
    - Serialize scoring data for external consumption.
    - Support automated reporting workflows.

    Attributes
    ----------
    _HTML_TEMPLATE : str
        Base HTML template used for report generation.
    """

    def __init__(self, manager: Optional[ScoreManager] = None) -> None:
        """Create a generator bound to ``manager`` (defaults to the singleton)."""
        self.manager = manager or ScoreManager()

    # -- snapshot -----------------------------------------------------------
    def build_snapshot(self, execution_id: str) -> Dict[str, Any]:
        """Return a nested dict describing the subtree rooted at ``execution_id``.

        Each node carries its local score, aggregate tree score, category
        breakdown, step counters, and recursively its children.
        """
        context = self.manager.get_context(execution_id)
        if context is None:
            raise KeyError(f"Unknown execution_id: {execution_id!r}")

        result = self.manager.calculate(execution_id)
        tree_score = self.manager.calculate_tree_score(execution_id)
        return {
            "execution_id": context.execution_id,
            "recipe_name": context.recipe_name,
            "local_score": round(result.final_score, 4),
            "tree_score": round(tree_score, 4),
            "profile_score": round(result.profile_score, 4),
            "total_steps": result.total_steps,
            "passed_steps": result.passed_steps,
            "categories": [c.to_dict() for c in result.categories],
            "children": [
                self.build_snapshot(child_id)
                for child_id in context.child_execution_ids
                if self.manager.get_context(child_id) is not None
            ],
        }

    # -- JSON ---------------------------------------------------------------
    def export_json(self, execution_id: str, *, indent: int = 2) -> str:
        """Return the full hierarchy as a pretty-printed JSON string."""
        return json.dumps(self.build_snapshot(execution_id), indent=indent)

    # -- Markdown -----------------------------------------------------------
    def export_markdown(self, execution_id: str) -> str:
        """Return a Markdown report with a per-recipe score table."""
        snapshot = self.build_snapshot(execution_id)
        lines: List[str] = ["# Recipe Execution Report", ""]
        self._markdown_node(snapshot, depth=0, lines=lines)
        return "\n".join(lines)

    def _markdown_node(
        self, node: Dict[str, Any], depth: int, lines: List[str]
    ) -> None:
        """Append a Markdown section for ``node`` and recurse into children."""
        heading = "#" * min(depth + 2, 6)
        lines.append(
            f"{heading} {node['recipe_name']} "
            f"(`{node['execution_id']}`) — {node['local_score']:.2f}"
        )
        lines.append("")
        lines.append("| Category | Score | Max | Status |")
        lines.append("| --- | ---: | ---: | :---: |")
        for cat in node["categories"]:
            if not cat["present"]:
                continue
            lines.append(
                f"| {cat['name']} | {cat['earned']:.2f} "
                f"| {cat['maximum']:.2f} | {cat['status']} |"
            )
        lines.append("")
        lines.append(f"- **Local score:** {node['local_score']:.2f}")
        lines.append(f"- **Tree score:** {node['tree_score']:.2f}")
        if node["profile_score"]:
            lines.append(f"- **Profile bonus:** {node['profile_score']:.2f}")
        lines.append("")
        for child in node["children"]:
            self._markdown_node(child, depth + 1, lines)

    # -- HTML ---------------------------------------------------------------
    def export_html(self, execution_id: str) -> str:
        """Return a self-contained HTML dashboard for the hierarchy."""
        snapshot = self.build_snapshot(execution_id)
        body = self._html_node(snapshot)
        return _HTML_TEMPLATE.format(
            title=html.escape(snapshot["recipe_name"]), body=body
        )

    def _html_node(self, node: Dict[str, Any]) -> str:
        """Render a single node (and its children) as an HTML card."""
        rows: List[str] = []
        for cat in node["categories"]:
            if not cat["present"]:
                continue
            status_class = {"PASS": "pass", "FAIL": "fail"}.get(cat["status"], "info")
            rows.append(
                "<tr>"
                f"<td>{html.escape(cat['name'])}</td>"
                f"<td class='num'>{cat['earned']:.2f}</td>"
                f"<td class='num'>{cat['maximum']:.2f}</td>"
                f"<td class='status {status_class}'>{html.escape(cat['status'])}</td>"
                "</tr>"
            )
        score = node["local_score"]
        score_class = "good" if score >= 90 else "warn" if score >= 70 else "bad"
        children_html = "".join(self._html_node(c) for c in node["children"])
        return f"""
        <div class="card">
          <div class="card-head">
            <h2>{html.escape(node['recipe_name'])}</h2>
            <span class="badge {score_class}">{score:.1f}</span>
          </div>
          <div class="meta">
            <code>{html.escape(node['execution_id'])}</code>
            &middot; tree {node['tree_score']:.1f}
            &middot; steps {node['passed_steps']}/{node['total_steps']}
          </div>
          <table>
            <thead><tr><th>Category</th><th>Score</th>
            <th>Max</th><th>Status</th></tr></thead>
            <tbody>{''.join(rows)}</tbody>
          </table>
          <div class="children">{children_html}</div>
        </div>
        """


